// Converts assets/icons/*.svg (duotone, fill="black") into typed React
// components that follow `currentColor`. Run: npm run icons
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const SRC = "assets/icons";
const OUT = "components/icons/generated.tsx";

const attrMap = {
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "fill-opacity": "fillOpacity",
  "stroke-opacity": "strokeOpacity",
  "clip-path": "clipPath",
};

function convert(svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 24 24";
  let inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();
  inner = inner
    .replace(/="(black|#000|#000000)"/gi, '="currentColor"')
    .replace(/\s(id|xmlns(:\w+)?)="[^"]*"/g, "");
  for (const [from, to] of Object.entries(attrMap)) {
    inner = inner.replaceAll(` ${from}=`, ` ${to}=`);
  }
  if (/<(clipPath|mask|defs|linearGradient|radialGradient)\b/.test(inner)) {
    throw new Error("Unsupported element (defs/clipPath/mask/gradient) — simplify the export");
  }
  return { viewBox, inner: inner.replace(/\n\s*/g, "") };
}

const files = readdirSync(SRC)
  .filter((f) => f.endsWith(".svg"))
  .sort();

const entries = files.map((f) => {
  const name = basename(f, ".svg");
  const { viewBox, inner } = convert(readFileSync(join(SRC, f), "utf8"));
  return `  "${name}": { viewBox: "${viewBox}", body: <>${inner}</> },`;
});

const out = `// AUTO-GENERATED by scripts/build-icons.mjs from assets/icons — do not edit.
import type { ReactElement } from "react";

export const iconData = {
${entries.join("\n")}
} satisfies Record<string, { viewBox: string; body: ReactElement }>;

export type IconName = keyof typeof iconData;
`;

writeFileSync(OUT, out);
console.log(`Generated ${files.length} icons → ${OUT}`);
