// Converts assets/logo.svg (a potrace bitmap trace) into a single-colour,
// tightly cropped React component. Run: npm run logo
//
// The trace draws a full-canvas rectangle with the letters cut out as holes.
// We drop that rectangle, make the next relative move absolute, merge every
// path with the even-odd rule, and crop the viewBox to the letters.
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "assets/logo.svg";
const OUT = "components/layout/logo-data.tsx";

const svg = readFileSync(SRC, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1].split(/[\s,]+/).map(Number);
const transform = svg.match(/<g[^>]*transform="([^"]+)"/)?.[1] ?? "";
const [tx, ty] = (transform.match(/translate\(([^)]+)\)/)?.[1] ?? "0,0").split(/[\s,]+/).map(Number);
const [sx, sy = sx] = (transform.match(/scale\(([^)]+)\)/)?.[1] ?? "1").split(/[\s,]+/).map(Number);
const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, " ").trim());

// Tokenise path data into [command, ...numbers] segments.
function parse(d) {
  return [...d.matchAll(/([MmLlCcZz])([^MmLlCcZz]*)/g)].map(([, c, args]) => [
    c,
    (args.match(/-?\d*\.?\d+(?:e-?\d+)?/gi) ?? []).map(Number),
  ]);
}

// Split a path into subpaths, tracking absolute start points.
function subpaths(d) {
  const out = [];
  let cx = 0, cy = 0, sx0 = 0, sy0 = 0, current = null;
  for (const [c, a] of parse(d)) {
    if (c === "M" || c === "m") {
      const x = c === "M" ? a[0] : cx + a[0];
      const y = c === "M" ? a[1] : cy + a[1];
      current = { start: [x, y], segs: [], points: [[x, y]] };
      out.push(current);
      cx = sx0 = x; cy = sy0 = y;
      for (let i = 2; i < a.length; i += 2) {
        cx = c === "M" ? a[i] : cx + a[i]; cy = c === "M" ? a[i + 1] : cy + a[i + 1];
        current.segs.push(["L", cx, cy]); current.points.push([cx, cy]);
      }
    } else if (c === "l" || c === "L") {
      for (let i = 0; i < a.length; i += 2) {
        cx = c === "L" ? a[i] : cx + a[i]; cy = c === "L" ? a[i + 1] : cy + a[i + 1];
        current.segs.push(["L", cx, cy]); current.points.push([cx, cy]);
      }
    } else if (c === "c" || c === "C") {
      for (let i = 0; i < a.length; i += 6) {
        const pts = [0, 2, 4].map((k) =>
          c === "C" ? [a[i + k], a[i + k + 1]] : [cx + a[i + k], cy + a[i + k + 1]],
        );
        current.segs.push(["C", ...pts.flat()]); current.points.push(...pts);
        [cx, cy] = pts[2];
      }
    } else {
      current.segs.push(["Z"]);
      cx = sx0; cy = sy0;
    }
  }
  return out;
}

const all = paths.flatMap(subpaths);
const [vx, vy, vw, vh] = viewBox;
const toView = ([x, y]) => [tx + sx * x, ty + sy * y];

// Drop the background rectangle: a subpath that covers the whole canvas.
const shapes = all.filter((p) => {
  const v = p.points.map(toView);
  const xs = v.map((q) => q[0]), ys = v.map((q) => q[1]);
  const covers = Math.min(...xs) <= vx + 1 && Math.max(...xs) >= vx + vw - 1 && Math.min(...ys) <= vy + 1 && Math.max(...ys) >= vy + vh - 1;
  return !covers;
});

const v = shapes.flatMap((p) => p.points.map(toView));
const pad = 4;
const minX = Math.floor(Math.min(...v.map((q) => q[0]))) - pad;
const minY = Math.floor(Math.min(...v.map((q) => q[1]))) - pad;
const w = Math.ceil(Math.max(...v.map((q) => q[0]))) + pad - minX;
const h = Math.ceil(Math.max(...v.map((q) => q[1]))) + pad - minY;

// Emit absolute coordinates already mapped into view space (no transform needed).
const r = (n) => Math.round(n * 10) / 10;
const d = shapes
  .map((p) => {
    const [x0, y0] = toView(p.start);
    const body = p.segs
      .map(([c, ...n]) => {
        if (c === "Z") return "Z";
        const pts = [];
        for (let i = 0; i < n.length; i += 2) pts.push(toView([n[i], n[i + 1]]).map(r).join(" "));
        return `${c}${pts.join(" ")}`;
      })
      .join("");
    return `M${r(x0)} ${r(y0)}${body}`;
  })
  .join("");

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/build-logo.mjs from assets/logo.svg — do not edit.
export const logoViewBox = "${minX} ${minY} ${w} ${h}";
export const logoAspect = ${(w / h).toFixed(4)};
export const logoPath =
  "${d}";
`,
);
console.log(`Logo: ${shapes.length} shapes, viewBox ${minX} ${minY} ${w} ${h} → ${OUT}`);
